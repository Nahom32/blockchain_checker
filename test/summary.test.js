import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { checkBlock, verifyFromCheckpoint, verifyRange } from '../src/chain.js';
import { checkBodyRoots } from '../src/body.js';
import { verifyHeaderHash } from '../src/header.js';
import { classifyProblem, detailsLine, failureBreakdown, formatDuration, retryCounter } from '../src/summary.js';

const load = (name) => JSON.parse(readFileSync(new URL(`./fixtures/${name}`, import.meta.url), 'utf8'));
const sequence = load('mainnet-sequence.json');
const genesis = load('mainnet-blocks.json').genesis;
const first = BigInt(sequence[0].number);
const byNumber = (blocks) => async (n) => blocks.find((b) => BigInt(b.number) === n) ?? null;

/** Every problem message the verifiers can produce, generated by the real code. */
async function realProblems() {
  const problems = {};
  const tampered = { ...sequence[1], gasUsed: '0x1' };
  problems.headerMismatch = checkBlock(tampered, null).problems[0];
  problems.headerUnbuildable = checkBlock({ ...sequence[1], gasUsed: '0xffffffffff' }, null).problems[0];
  problems.genesis = checkBlock({ ...genesis, parentHash: `0x${'11'.repeat(32)}` }, null).problems.at(-1);
  problems.wrongNumber = checkBlock(sequence[2], checkBlock(sequence[0], null)).problems[0];

  const forged = { ...sequence[2], miner: '0x000000000000000000000000000000000000dead' };
  forged.hash = verifyHeaderHash(forged).expected;
  const linkRun = await verifyRange({
    from: first, to: first + 3n, fetchBlock: byNumber([sequence[0], sequence[1], forged, sequence[3]]),
  });
  problems.parentHash = linkRun.failed[0].problems[0];
  const missingRun = await verifyRange({ from: first, to: first + 1n, fetchBlock: byNumber([sequence[0]]) });
  problems.missing = missingRun.failed[0].problems[0];

  const top = sequence.at(-1);
  const badCheckpoint = await verifyFromCheckpoint({
    checkpointHash: `0x${'ab'.repeat(32)}`, checkpointBlock: top, from: first, fetchBlock: byNumber(sequence),
  });
  problems.notCheckpoint = badCheckpoint.failed[0].problems[0];
  const wrongBlock = await verifyFromCheckpoint({
    checkpointHash: top.hash, checkpointBlock: top, from: first, fetchBlock: async () => sequence[0],
  });
  problems.askedFor = wrongBlock.failed[0].problems[0];
  // Block 3 forged (self-consistent): it can't match the parentHash its trusted child commits to.
  const forged3 = { ...sequence[3], miner: '0x000000000000000000000000000000000000dead' };
  forged3.hash = verifyHeaderHash(forged3).expected;
  const brokenTrust = await verifyFromCheckpoint({
    checkpointHash: top.hash, checkpointBlock: top, from: first, fetchBlock: byNumber([...sequence.slice(0, 3), forged3]),
  });
  problems.trust = brokenTrust.failed[0].problems[0];

  const full = load('mainnet-full-blocks.json').allModernTypes;
  const receipts = load('mainnet-receipts.json').allModernTypes;
  const editedTxs = structuredClone(full.transactions);
  editedTxs[0].value = '0x1';
  const bodyProblems = await checkBodyRoots(
    { ...full, transactions: editedTxs, withdrawals: full.withdrawals.slice(1) },
    receipts.slice(1),
  );
  [problems.txRoot, problems.receiptsRoot, problems.withdrawalsRoot] = bodyProblems;
  return problems;
}

test('every problem the verifiers produce is classified', async () => {
  const problems = await realProblems();
  const expected = {
    headerMismatch: 'header', headerUnbuildable: 'header',
    genesis: 'link', wrongNumber: 'link', parentHash: 'link', notCheckpoint: 'link', askedFor: 'link', trust: 'link',
    missing: 'missing', txRoot: 'body', receiptsRoot: 'body', withdrawalsRoot: 'body',
  };
  for (const [name, kind] of Object.entries(expected)) {
    assert.ok(problems[name], `no ${name} problem was produced`);
    assert.equal(classifyProblem(problems[name]), kind, `${name}: "${problems[name]}"`);
  }
  assert.equal(classifyProblem('something new'), 'other');
});

test('failures are counted per block by kind', () => {
  const failed = [
    { problems: ['header hash mismatch: x', 'parentHash 0x1 does not match y'] },
    { problems: ['parentHash 0x2 does not match z'] },
    { problems: ['transactions root mismatch: a', 'receipts root mismatch: b'] },
  ];
  assert.equal(failureBreakdown(failed), '1 header hash mismatch, 2 broken links, 1 contents mismatch');
});

test('durations and details read naturally', () => {
  assert.equal(formatDuration(3240), '3.2s');
  assert.equal(formatDuration(199_000), '3m 19s');

  const retries = retryCounter();
  assert.equal(detailsLine({ from: 5n, to: 9n, elapsedMs: 1500, retries }), '  Blocks 5 to 9 in 1.5s.');
  retries.onRetry({ label: 'eth.drpc.org' });
  retries.onRetry({ label: 'eth.drpc.org' });
  retries.onRetry({ label: 'node.example' });
  assert.equal(retries.total(), 3);
  assert.equal(
    detailsLine({ from: 5n, to: 9n, elapsedMs: 1500, retries }),
    '  Blocks 5 to 9 in 1.5s; eth.drpc.org retried 2 requests, node.example retried 1 request.',
  );
});
